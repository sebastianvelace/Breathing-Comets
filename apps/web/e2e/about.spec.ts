import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";

const atlas = JSON.parse(readFileSync("static/data/comets/index.json", "utf8"));

test("about page states what it is, the challenge, the credits and the AI use", async ({ page }) => {
  await page.goto("/about");
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("About");
  await expect(page.locator("main section")).toHaveCount(6);
  await expect(page.getByText("Planet X and SPHEREx", { exact: false })).toBeVisible();
  await expect(page.getByText("not a NASA product", { exact: false })).toBeVisible();
  await expect(page.getByText("No image on this site is generated by AI", { exact: false })).toBeVisible();
  const table = page.getByTestId("about-sources");
  for (const id of ["spherex", "hips", "gaia", "wise", "jpl", "simbad", "aladin", "astropy"])
    await expect(table.locator(`tr[data-source="${id}"]`)).toHaveCount(1);
  await expect(table).toContainText("ESA/Gaia/DPAC");
  await expect(table).toContainText("NASA/JPL-Caltech/IRSA");
});

test("figures on the page come from the data and links resolve", async ({ page, request }) => {
  await page.goto("/about");
  await expect(page.getByRole("link", { name: new RegExp(`CO₂ released by ${atlas.counts.comets} comets`) })).toBeVisible();
  await expect(page.getByText("102 colors", { exact: false })).toBeVisible();
  const hrefs = await page.locator("main a[href^='/']").evaluateAll((as) => as.map((a) => a.getAttribute("href")!));
  expect(hrefs.length).toBeGreaterThanOrEqual(4);
  for (const href of new Set(hrefs)) expect((await request.get(href)).status(), href).toBe(200);
});

test("Spanish about page and mobile layout", async ({ page }) => {
  await page.goto("/es/about");
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("Acerca de");
  await expect(page.getByText("Ninguna imagen de este sitio la genera una IA", { exact: false })).toBeVisible();
  expect(await page.locator("main").innerText()).not.toMatch(/\d,\d/);
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/es/about");
  const { sw, cw } = await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, cw: document.documentElement.clientWidth }));
  expect(sw).toBeLessThanOrEqual(cw);
});

test("landing footer and method link to about", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("link", { name: "About", exact: true }).click();
  await expect(page).toHaveURL(/\/about$/);
  await page.goto("/method");
  await page.getByRole("link", { name: "About", exact: true }).click();
  await expect(page).toHaveURL(/\/about$/);
});
